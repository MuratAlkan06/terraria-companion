/**
 * Human-readable gap report (Markdown) generated from the same inputs as gaps.json — AMENDMENTS-001
 * A2 AC3 / PRD "dataset gap report". Deterministic for a given raw cache + overlays.
 */
import type { GapEntry, Gaps, Meta } from '../../src/schemas'
import type { PipelineWarning } from '../validate/errors'
import type { EmittedFile } from './write'

export interface ReportInput {
  meta: Meta
  gaps: Gaps
  warnings: readonly PipelineWarning[]
  reconciliation: { title: string; rows: [string, string | number][] }[]
  reasonTallies: { title: string; tally: ReadonlyMap<string, { count: number; examples: string[] }> }[]
  ambiguousNames: ReadonlyMap<string, number[]>
  /** "entity · field" → number of records listing that field in _prov.unverifiedFields. */
  unknownFields: ReadonlyMap<string, number>
  resolutions: { id: string; text: string }[]
  files: readonly EmittedFile[]
  fetch?: { networkAttempts: number; note: string }
}

const esc = (s: string) => s.replaceAll('|', '\\|').replaceAll('\n', ' ')

export function renderGapReport(r: ReportInput): string {
  const out: string[] = []
  const { meta, gaps } = r
  out.push('# Dataset gap report — wiki sync (P2-S2a)', '')
  out.push(`Generated by \`npm run pipeline:build\` — do not edit by hand. Terraria ${meta.gameVersion}; data as of ${meta.generatedAt}; Module:Iteminfo/data rev ${meta.iteminfo.rev} (synced to ${meta.iteminfo.syncedTo}).`, '')
  if (r.fetch) out.push(`Fetch: ${r.fetch.networkAttempts} network requests logged in pipeline/raw/requests.log.jsonl (${r.fetch.note}).`, '')

  out.push('## Count reconciliation (Cargo → emitted)', '')
  for (const t of r.reconciliation) {
    out.push(`### ${t.title}`, '', '| | |', '|---|---:|')
    for (const [k, v] of t.rows) out.push(`| ${esc(k)} | ${v} |`)
    out.push('')
  }

  out.push('## Records and unknown fields', '', '| Entity | Records | Verified | With unverified fields |', '|---|---:|---:|---:|')
  for (const [k, v] of Object.entries(gaps.summary.perEntity)) if (v.total > 0) out.push(`| ${k} | ${v.total} | ${v.verified} | ${v.withUnverifiedFields} |`)
  out.push('')
  out.push('Unknown (absent + listed) fields, by entity · field — each renders "Unknown" in the UI:', '', '| Entity · field | Records |', '|---|---:|')
  for (const [k, v] of [...r.unknownFields].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))) out.push(`| ${esc(k)} | ${v} |`)
  out.push('')

  out.push(`gaps.json: ${gaps.entries.length} entries — ${Object.entries(meta.gapSummary.byKind).map(([k, n]) => `${k} ${n}`).join(', ')}.`, '')

  for (const t of r.reasonTallies) {
    if (t.tally.size === 0) continue
    out.push(`## ${t.title}`, '', '| Reason | Rows | Examples |', '|---|---:|---|')
    for (const [reason, { count, examples }] of [...t.tally].sort((a, b) => b[1].count - a[1].count)) out.push(`| ${esc(reason)} | ${count} | ${esc(examples.join('; '))} |`)
    out.push('')
  }

  const rowGaps = gaps.entries.filter((e) => e.ref.includes(':cargo-row-') || e.kind === 'source-mismatch')
  out.push('## Rows not emitted and cross-check findings', '')
  if (rowGaps.length === 0) out.push('None.', '')
  else {
    out.push('| Ref | Kind | Detail |', '|---|---|---|')
    for (const e of rowGaps.sort((a: GapEntry, b: GapEntry) => a.ref.localeCompare(b.ref))) out.push(`| ${e.ref} | ${e.kind} | ${esc(e.detail)} |`)
    out.push('')
  }

  out.push('## Duplicate display names resolved via the wiki\'s nameDB', '')
  if (r.ambiguousNames.size === 0) out.push('None referenced.', '')
  else {
    out.push('Module:Iteminfo/data has several items with these exact names; references use the wiki\'s own `nameDB.itemIdFromName` choice.', '', '| Name | Item IDs with that name |', '|---|---|')
    for (const [name, ids] of [...r.ambiguousNames].sort()) out.push(`| ${esc(name)} | ${ids.join(', ')} |`)
    out.push('')
  }

  out.push('## Deferred references (partial dataset)', '')
  const deferred = r.warnings.filter((w) => w.code === 'W_DEFERRED_REF')
  if (deferred.length === 0) out.push('None.', '')
  for (const w of deferred) out.push(`- ${esc(w.message)}`)
  out.push('')

  out.push('## TO-VERIFY-IN-P2 resolutions', '')
  for (const v of r.resolutions) out.push(`- **${v.id}** — ${v.text}`)
  out.push('')

  out.push('## Emitted files', '', '| File | Bytes | Gzip bytes |', '|---|---:|---:|')
  for (const f of r.files) out.push(`| ${f.file} | ${f.bytes} | ${f.gzBytes} |`)
  out.push('')
  return out.join('\n')
}
